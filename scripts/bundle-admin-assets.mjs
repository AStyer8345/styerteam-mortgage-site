import fs from 'node:fs';
const files = JSON.parse(fs.readFileSync('scripts/admin-paths.json', 'utf8'));
const assets = Object.fromEntries(files.map(file => ['/' + file, {
  body: fs.readFileSync(file, 'utf8'),
  type: file.endsWith('.html') ? 'text/html; charset=utf-8' : file.endsWith('.css') ? 'text/css; charset=utf-8' : file.endsWith('.js') ? 'text/javascript; charset=utf-8' : 'application/json; charset=utf-8'
}]));
fs.mkdirSync('netlify/functions/_shared', {recursive:true});
fs.writeFileSync('netlify/functions/_shared/admin-assets.ts', '// Generated by scripts/bundle-admin-assets.mjs. Never publish statically.\nexport const adminAssets: Record<string,{body:string;type:string}> = ' + JSON.stringify(assets) + ';\n');
console.log(`Bundled ${files.length} private administrative assets.`);
