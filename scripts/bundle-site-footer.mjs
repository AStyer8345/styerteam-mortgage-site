import fs from 'node:fs';
// Compile the canonical HTML into the runtime so imports never depend on Lambda cwd.
const footer=fs.readFileSync('netlify/functions/lib/site-footer.html','utf8').trim();
fs.writeFileSync('netlify/functions/lib/site-footer-content.js','// Generated by scripts/bundle-site-footer.mjs from site-footer.html.\nmodule.exports = '+JSON.stringify(footer)+';\n');
console.log('Bundled shared site footer for serverless publishing.');
